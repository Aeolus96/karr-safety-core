#!/usr/bin/env python3
"""Generate docs/diagrams/05-rc-channel-map.d2 from source modules.

Parses RC_CHANNEL_CONFIGURATION[] from src/rc_receiver.cpp and
SWITCH_TO_RELAY_BINDINGS[] from src/relay_feature_controller.cpp so the
channel/binding diagram can never drift from the source tables.

Usage:
    python3 docs/diagrams/gen_rc_map.py            # regenerates + renders .svg (needs d2)
    python3 docs/diagrams/gen_rc_map.py --check    # CI mode: exit 1 if .d2 is stale

Hook it up (optional):
    # .git/hooks/pre-commit (or CI step): python3 docs/diagrams/gen_rc_map.py --check
"""
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RC_RECEIVER = ROOT / "src" / "rc_receiver.cpp"
RELAY_FEATURE_CONTROLLER = ROOT / "src" / "relay_feature_controller.cpp"
OUT_D2 = ROOT / "docs" / "diagrams" / "05-rc-channel-map.d2"


def main() -> int:
    check_only = "--check" in sys.argv

    rc_text = RC_RECEIVER.read_text()
    controller_text = RELAY_FEATURE_CONTROLLER.read_text()

    channels_body = re.search(
        r"RC_CHANNEL_CONFIGURATION\[RC_CHANNEL_COUNT\]\s*=\s*\{(.*?)\};", rc_text, re.DOTALL
    ).group(1)
    channel_rows = re.findall(
        r'\{\s*"([^"]+)"\s*,\s*ChannelKind::(\w+)', channels_body
    )
    if len(channel_rows) != 10:
        print("warning: expected 10 channels, parsed", len(channel_rows))

    bindings_body = re.search(
        r"SWITCH_TO_RELAY_BINDINGS\[\]\s*=\s*\{(.*?)\};", controller_text, re.DOTALL
    ).group(1)
    bindings = re.findall(
        r'\{\s*(\d+)\s*,\s*(\d+)\s*,\s*"([^"]+)"\s*\}', bindings_body
    )

    estop_m = re.search(r"ESTOP_CHANNEL_INDEX\s*=\s*(\d+)", rc_text)
    estop_idx = int(estop_m.group(1)) if estop_m else 5

    lines = [
        "# GENERATED by docs/diagrams/gen_rc_map.py from src modules - DO NOT EDIT.",
        "# Re-run: python3 docs/diagrams/gen_rc_map.py",
        "direction: right",
        "",
        'title: "RC channel map - generated from src modules" {',
        "  shape: text",
        "}",
        "",
    ]
    bound_relays = sorted(set(int(r) for _, r, _ in bindings))
    for i, (name, kind) in enumerate(channel_rows, start=1):
        idx = i - 1
        if kind == "AnalogAxis":
            short = "analog"
        elif kind == "TwoPositionSwitch":
            short = "2-pos"
        elif kind == "ThreePositionSwitch":
            short = "3-pos"
        else:
            short = kind
        label = f"ch{i} {name}\\n{short}"
        attrs = []
        if idx == estop_idx:
            attrs.append('style.fill: "#ffcdd2"')
            attrs.append("style.stroke-width: 3")
            label += "\\nSAFETY-RESERVED"
        elif short == "analog":
            attrs.append('style.fill: "#e3f2fd"')
        else:
            attrs.append('style.fill: "#e8f5e9"')
        attr_str = (" {\n  " + "\n  ".join(attrs) + "\n}") if attrs else ""
        lines.append(f'ch{i}: "{label}"{attr_str}')
    lines.append("")

    for r in bound_relays:
        lines.append('relay' + str(r + 1) + ': "relay ' + str(r + 1) + '" {')
        lines.append("  shape: cylinder")
        lines.append("}")
    lines.append("")

    for ch_idx, relay_idx, feat in bindings:
        lines.append(
            "ch" + str(int(ch_idx) + 1) + " -> relay" + str(int(relay_idx) + 1)
            + ': "' + feat + '"'
        )
    lines.append("")

    lines.append("ch" + str(estop_idx + 1) + " -> note: \"never bound\" {")
    lines.append("  style.stroke-dash: 2")
    lines.append('  style.font-color: "#b71c1c"')
    lines.append("}")
    lines.append('note: "ch6 LOW = e-stop ENGAGED" { shape: text }')
    lines.append("")

    new_content = "\n".join(lines)
    if check_only:
        current = OUT_D2.read_text() if OUT_D2.exists() else ""
        if current != new_content:
            print("STALE: diagram differs from source modules")
            return 1
        print("OK: channel map matches source modules")
        return 0

    OUT_D2.write_text(new_content)
    print("wrote " + str(OUT_D2.relative_to(ROOT)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
