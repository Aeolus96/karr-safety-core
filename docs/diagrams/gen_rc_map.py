#!/usr/bin/env python3
"""Generate docs/diagrams/05-rc-channel-map.d2 from src/main.cpp.

Parses RC_CHANNEL_CONFIGURATION[] and SWITCH_TO_RELAY_BINDINGS[] so the
channel/binding diagram can never drift from the source tables.

Usage:
    python3 docs/diagrams/gen_rc_map.py            # regenerates + renders .svg (needs d2)
    python3 docs/diagrams/gen_rc_map.py --check    # CI mode: exit 1 if .d2 is stale

Hook it up (optional):
    # .git/hooks/pre-commit (or CI step): python3 docs/diagrams/gen_rc_map.py --check
"""
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MAIN = ROOT / "src" / "main.cpp"
OUT_D2 = ROOT / "docs" / "diagrams" / "05-rc-channel-map.d2"


def parse_table(pattern: str, text: str) -> str:
    m = re.search(pattern, text, re.DOTALL)
    if not m:
        raise SystemExit(f"pattern not found: {pattern[:60]}...")
    return m.group(1)


def main() -> int:
    check_only = "--check" in sys.argv
    text = MAIN.read_text()

    channels_body = parse_table(
        r"RC_CHANNEL_CONFIGURATION\[RC_CHANNEL_COUNT\]\s*=\s*\{(.*?)\};", text
    )
    channel_rows = re.findall(
        r'\{\s*"([^"]+)"\s*,\s*ChannelKind::(\w+)', channels_body
    )
    if len(channel_rows) != 10:
        print(f"warning: expected 10 channels, parsed {len(channel_rows)}")

    bindings_body = parse_table(
        r"SWITCH_TO_RELAY_BINDINGS\[\]\s*=\s*\{(.*?)\};", text
    )
    bindings = re.findall(
        r'\{\s*(\d+)\s*,\s*(\d+)\s*,\s*"([^"]+)"\s*\}', bindings_body
    )

    estop_m = re.search(r"ESTOP_CHANNEL_INDEX\s*=\s*(\d+)", text)
    estop_idx = int(estop_m.group(1)) if estop_m else 5

    lines = [
        "# GENERATED by tools/gen_rc_map.py from src/main.cpp — DO NOT EDIT.",
        "# Re-run: python3 tools/gen_rc_map.py",
        "direction: right",
        "",
        'title: "RC channel map — generated from src/main.cpp" {',
        "  shape: text",
        "}",
        "",
    ]
    bound_relays = {int(r) for _, r, _ in bindings}
    for i, (name, kind) in enumerate(channel_rows, start=1):
        idx = i - 1
        short_kind = {"AnalogAxis": "analog", "TwoPositionSwitch": "2-pos",
                      "ThreePositionSwitch": "3-pos"}.get(kind, kind)
        label = f"ch{i} {name}\\n{short_kind}"
        attrs = []
        if idx == estop_idx:
            attrs.append('style.fill: "#ffcdd2"')
            attrs.append("style.stroke-width: 3")
            label += "\\nSAFETY-RESERVED"
        elif short_kind == "analog":
            attrs.append('style.fill: "#e3f2fd"')
        else:
            attrs.append('style.fill: "#e8f5e9"')
        attr_str = (" {\n  " + "\n  ".join(attrs) + "\n}") if attrs else ""
        lines.append(f"ch{i}: \"{label}\"{attr_str}")
    lines.append("")
    for r in sorted(bound_relays):
        lines.append(f"relay{r + 1}: \"relay {r + 1}\" {{\n  shape: cylinder\n}}")
    lines.append("")
    for ch_idx, relay_idx, feat in bindings:
        lines.append(
            f"ch{int(ch_idx) + 1} -> relay{int(relay_idx) + 1}: \"{feat}\""
        )
    lines.append("")
    lines.append(f"ch{estop_idx + 1} -> note: \"never bound\" {{")
    lines.append('  style.stroke-dash: 2')
    lines.append('  style.font-color: "#b71c1c"')
    lines.append("}")
    lines.append('note: "ch6 LOW = e-stop ENGAGED" { shape: text }')
    lines.append("")

    new_content = "\n".join(lines)
    if check_only:
        current = OUT_D2.read_text() if OUT_D2.exists() else ""
        if current != new_content:
            print("STALE: 05-rc-channel-map.d2 differs from src/main.cpp — "
                  "run python3 docs/diagrams/gen_rc_map.py")
            return 1
        print("OK: channel map diagram matches src/main.cpp")
        return 0

    OUT_D2.write_text(new_content)
    print(f"wrote {OUT_D2.relative_to(ROOT)} "
          f"({len(channel_rows)} channels, {len(bindings)} bindings)")
    try:
        subprocess.run(["d2", str(OUT_D2), str(OUT_D2.with_suffix(".svg"))],
                       check=True)
        print("rendered svg")
    except (subprocess.CalledProcessError, FileNotFoundError) as e:
        print(f"note: svg render skipped ({e})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
